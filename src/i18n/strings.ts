export const STRINGS = { ar: AR, en: EN } as const;
export type TranslationKey = keyof typeof AR;

export function t(language: Language, key: TranslationKey): string {
  return STRINGS[language][key];
}

const DAY_KEYS: Record<Weekday, TranslationKey> = {
  1: 'daySunday', 2: 'dayMonday', 3: 'dayTuesday', 4: 'dayWednesday',
  5: 'dayThursday', 6: 'dayFriday', 7: 'daySaturday',
};

export function dayLabel(lang: Language, weekday: Weekday): string {
  return t(lang, DAY_KEYS[weekday]);
}

export function formatNumber(value: number, lang: Language): string {
  return new Intl.NumberFormat(lang === 'ar' ? 'ar-EG' : 'en-US', { maximumFractionDigits: 0 }).format(value);
}

export function progressLabel(lang: Language, checked: number, total: number): string {
  if (lang === 'ar') return `${formatNumber(checked, lang)} من ${formatNumber(total, lang)}`;
  return `${checked} of ${total}`;
}

export function formatTime(hour: number, minute: number, lang: Language): string {
  const h = hour % 12 || 12;
  const period = hour < 12 ? (lang === 'ar' ? 'ص' : 'AM') : (lang === 'ar' ? 'م' : 'PM');
  const time = `${formatNumber(h, lang)}:${formatNumber(minute, lang).padStart(2, lang === 'ar' ? '٠' : '0')}`;
  return `${time} ${period}`;
}

export function formatWeekdays(lang: Language, weekdays: readonly Weekday[]): string {
  return weekdays.map(day => dayLabel(lang, day)).join(lang === 'ar' ? '، ' : ', ');
}

/** One localized cadence summary for home cards and list details. */
export function formatListSchedule(lang: Language, schedule: ListSchedule): string {
  const time = formatTime(schedule.hour, schedule.minute, lang);
  if (schedule.cadence === 'monthly') {
    return `${t(lang, 'cadenceMonthly')} · ${t(lang, 'monthlyDayLabel')} ${formatNumber(schedule.dayOfMonth ?? 1, lang)} · ${time}`;
  }
  return `${t(lang, 'cadenceWeekly')} · ${formatWeekdays(lang, schedule.weekdays)} · ${time}`;
}
