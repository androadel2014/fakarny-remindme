// Fakarny v1.1.9 — targeted fix for the PROVEN launch crash.
//
// Crashlytics (v1.1.8, issue e5d2e3de9ccc548974f49e37701c10a3):
//   RuntimeException: Unable to get provider androidx.startup.InitializationProvider
//   Caused by: Failed to create an instance of androidx.work.impl.WorkDatabase
//   (WorkManagerInitializer -> WorkDatabase creation during androidx.startup,
//    before any JS runs.)
//
// Root cause: react-native-google-mobile-ads pulls in androidx.work
// (WorkManager) + Room. Room instantiates the generated class
// androidx.work.impl.WorkDatabase_Impl reflectively; in release builds R8
// strips/renames it, so WorkDatabase creation fails at startup. Removing the
// ads init provider (v1.1.5) or disabling JS (v1.1.4) could never help; only
// removing the whole ads package (v1.1.2/v1.1.7) avoided the code path.
//
// Fix: append R8/ProGuard keep rules for WorkManager/Room/Ads to
// android/app/proguard-rules.pro at prebuild time.
//
// NOTE: @expo/config-plugins@58 no longer ships withProguardRules, so this
// uses withDangerousMod (runs after the android project is generated, before
// Gradle) — the supported mechanism on SDK 58. android/ is regenerated by CI
// on every build (gitignored), so this plugin is the carrier of the rules.
const { withDangerousMod } = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

const KEEP_RULES = `
# --- Fakarny v1.1.9: WorkManager/Room + Ads R8 keep rules (Crashlytics-proven fix) ---
-keep class androidx.work.impl.WorkDatabase_Impl { *; }
-keep class androidx.work.** { *; }
-keep class * extends androidx.room.RoomDatabase { *; }
-keep class **_Impl { *; }
-keep class com.google.android.gms.ads.** { *; }
`;

const withAndroidKeeps = (config) => {
  return withDangerousMod(config, [
    'android',
    async (config) => {
      const proguardPath = path.join(
        config.modRequest.platformProjectRoot,
        'app',
        'proguard-rules.pro'
      );
      let contents = '';
      if (fs.existsSync(proguardPath)) {
        contents = fs.readFileSync(proguardPath, 'utf8');
      }
      if (!contents.includes('androidx.work.impl.WorkDatabase_Impl')) {
        fs.mkdirSync(path.dirname(proguardPath), { recursive: true });
        const base = contents.replace(/\s*$/, '');
        fs.writeFileSync(proguardPath, (base ? base + '\n' : '') + KEEP_RULES);
      }
      return config;
    },
  ]);
};

module.exports = withAndroidKeeps;
